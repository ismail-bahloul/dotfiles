#!/usr/bin/env python3
# kitty-material-you.py
# Aligns kitty with the Material You colors of the wallpaper, via the Konsole
# colorscheme that kde-material-you-colors regenerates (kitty == Konsole).
# Writes ~/.config/kitty/theme-wallpaper.conf  (included by kitty.conf)
import os
import sys

import material_you_lib as my

OUT = os.path.expanduser('~/.config/kitty/theme-wallpaper.conf')


def main():
    p = my.palette_or_die()
    bg, fg = p['bg'], p['fg']
    colors = p['base'] + p['intense']
    accent = colors[1]  # Color1 = Material You accent (follows the wallpaper)
    L = ['# generated by kitty-material-you.py (Konsole colorscheme / kde-material-you-colors)',
         'background               ' + bg,
         'foreground               ' + fg,
         'cursor                   ' + accent,
         'cursor_text_color        ' + bg,
         'selection_background     ' + colors[6],
         'selection_foreground     ' + bg]
    for i, c in enumerate(colors):
        L.append('color%-6d %s' % (i, c))
    open(OUT, 'w').write('\n'.join(L) + '\n')
    print('kitty theme written (== Konsole). bg=%s fg=%s cursor=%s' % (bg, fg, accent))
    return 0


if __name__ == '__main__':
    sys.exit(main())
