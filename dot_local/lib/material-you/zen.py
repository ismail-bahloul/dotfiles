#!/usr/bin/env python3
# zen.py
# Aligns Zen Browser with the Material You colors:
#   - zen.theme.accent-color (+ use-system-colors) in the profile's user.js,
#   - chrome/zen-material-you.css (userChrome) overriding the surfaces, because
#     Zen only mixes 20-30% of the accent over near-black in dark mode and keeps
#     fixed greys for the big areas,
#   - chrome/zen-material-you-content.css (userContent) for about:newtab.
# Zen reads user.js and userChrome.css at startup -> restart Zen to apply.
# Use `zen.py --remove` to drop the generated block and stylesheets.
import configparser
import os
import sys

import material_you_lib as my

BEGIN = '// >>> material-you (generated) >>>'
END = '// <<< material-you (generated) <<<'


def zen_profile():
    """Active Zen profile directory (the one the launcher uses), or None."""
    root = os.path.expanduser('~/.config/zen')
    ini = os.path.join(root, 'profiles.ini')
    if os.path.isfile(ini):
        c = configparser.ConfigParser(strict=False)
        c.read(ini)
        # [Install*] names the profile the launcher actually uses; then [Profile*].
        sections = [s for s in c.sections() if s.startswith('Install')]
        sections += [s for s in c.sections() if s.startswith('Profile')]
        for section in sections:
            key = 'Default' if c.has_option(section, 'Default') else 'Path'
            if not c.has_option(section, key):
                continue
            path = c.get(section, key)
            if c.get(section, 'IsRelative', fallback='1') != '0':
                path = os.path.join(root, path)
            if os.path.isfile(os.path.join(path, 'prefs.js')):
                return path
    # Fallback: most recently used profile that already has a prefs.js.
    if os.path.isdir(root):
        candidates = [
            os.path.join(root, d) for d in os.listdir(root)
            if os.path.isfile(os.path.join(root, d, 'prefs.js'))
        ]
        if candidates:
            return max(candidates, key=os.path.getmtime)
    return None


def colours(p):
    """Palette roles and the surfaces Zen needs (mix() semantics: t=1 -> b)."""
    bg, fg = p['bg'], p['fg']
    accent = p['base'][1]
    mix = my.mix
    # BackgroundIntense is the "elevated surface" tone generated by
    # kde-material-you-colors; using it keeps the sidebar distinct from the page.
    surface = p.get('bg_intense') or mix(bg, fg, 0.06)
    secondary = mix(accent, bg, 0.65)
    return {
        'bg': bg,
        'fg': fg,
        'accent': accent,
        'primary': mix(accent, bg, 0.80),
        'secondary': secondary,
        'tertiary': mix(accent, bg, 0.97),
        'hover': mix(accent, bg, 0.50),
        'primary_fg': mix(accent, '#ffffff', 0.20),
        'border': p.get('bg_faint') or mix('#4f4f4f', secondary, 0.20),
        'surface': surface,
        'surface_hi': mix(surface, fg, 0.07),
        'input': mix(surface, fg, 0.10),
        'muted': mix(fg, bg, 0.45),
    }


def user_chrome_css(c):
    # `*` (not `:root`): Zen sets these variables inline on descendant elements
    # (#zen-browser-background, the space element, ...) when a workspace theme
    # exists, and an inline value on an element wins over the inherited one.
    # A user-important declaration on every element wins over those, and
    # --zen-background-opacity: 1 removes the workspace theme's 50 % wash.
    return """/* generated by zen.py - do not edit */
* {
  --zen-branding-dark: %(bg)s !important;
  --zen-branding-paper: %(bg)s !important;
  --zen-primary-color: %(accent)s !important;
  --zen-main-browser-background: %(surface)s !important;
  --zen-main-browser-background-toolbar: %(surface)s !important;
  --zen-themed-toolbar-bg-transparent: %(bg)s !important;
  --zen-background-opacity: 1 !important;
  --zen-grainy-background-opacity: 0 !important;
  --toolbox-textcolor: %(fg)s !important;
  --toolbar-color: %(fg)s !important;
  --zen-colors-primary: %(primary)s !important;
  --zen-colors-secondary: %(secondary)s !important;
  --zen-colors-tertiary: %(tertiary)s !important;
  --zen-colors-hover-bg: %(hover)s !important;
  --zen-colors-primary-foreground: %(primary_fg)s !important;
  --zen-colors-border: %(border)s !important;
  --zen-colors-input-bg: %(input)s !important;
  --zen-toolbar-element-bg: %(primary)s !important;
  --tab-background-color-selected: %(secondary)s !important;
  --tab-text-color-selected: %(fg)s !important;
  --zen-dialog-background: %(surface)s !important;
  --zen-urlbar-background: %(surface_hi)s !important;
  --arrowpanel-background: %(surface)s !important;
  --in-content-page-background: %(bg)s !important;
  --in-content-page-color: %(fg)s !important;
  --lwt-accent-color: %(bg)s !important;
  --lwt-text-color: %(fg)s !important;
  --toolbar-field-background-color: %(input)s !important;
  --toolbar-field-color: %(fg)s !important;
}

#tabbrowser-tabpanels .browserSidebarContainer
  browser[type="content"]:not([transparent="true"]) {
  background: %(bg)s !important;
}
""" % c


def user_content_css(c):
    return """/* generated by zen.py - do not edit */
@-moz-document url("about:newtab"), url("about:home"), url("about:blank"), url("about:privatebrowsing") {
  :root {
    --newtab-background-color: %(bg)s !important;
    --newtab-background-color-secondary: %(input)s !important;
    --newtab-text-primary-color: %(fg)s !important;
    --newtab-text-secondary-color: %(muted)s !important;
    --newtab-primary-action-background: %(accent)s !important;
    --newtab-primary-element-hover-color: %(hover)s !important;
    --newtab-element-hover-color: %(secondary)s !important;
    --newtab-search-border-color: %(border)s !important;
    --newtab-search-icon-color: %(fg)s !important;
    --newtab-border-color: %(border)s !important;
  }
  body, .outer-wrapper {
    background-color: %(bg)s !important;
  }
}
""" % c


def write_user_js(profile, accent):
    """Replace our generated block, preserving anything else in user.js."""
    path = os.path.join(profile, 'user.js')
    try:
        current = open(path).read()
    except FileNotFoundError:
        current = ''
    begin = current.find(BEGIN)
    end = current.find(END)
    if begin != -1 and end != -1:
        current = current[:begin] + current[end + len(END):]
    current = current.strip('\n')
    block = '\n'.join([
        BEGIN,
        'user_pref("zen.theme.accent-color", "%s");' % accent,
        'user_pref("zen.theme.use-system-colors", true);',
        'user_pref("toolkit.legacyUserProfileCustomizations.stylesheets", true);',
        END,
    ])
    with open(path, 'w') as f:
        f.write((current + '\n\n' if current else '') + block + '\n')


def remove_user_js_block(profile):
    """Drop our generated block, keeping any other pref. Delete an empty file."""
    path = os.path.join(profile, 'user.js')
    try:
        current = open(path).read()
    except FileNotFoundError:
        return False
    begin = current.find(BEGIN)
    end = current.find(END)
    if begin == -1 or end == -1:
        return False
    rest = (current[:begin] + current[end + len(END):]).strip('\n')
    if rest:
        with open(path, 'w') as f:
            f.write(rest + '\n')
    else:
        os.remove(path)
    return True


def remove_import(path, target):
    """Remove our `@import` line; delete the file if nothing else is left."""
    try:
        current = open(path).read()
    except FileNotFoundError:
        return False
    line = '@import url("%s");' % target
    if line not in current:
        return False
    rest = '\n'.join(l for l in current.splitlines() if l.strip() != line).strip('\n')
    if rest:
        with open(path, 'w') as f:
            f.write(rest + '\n')
    else:
        os.remove(path)
    return True


def remove_theme(profile):
    chrome = os.path.join(profile, 'chrome')
    removed = []
    if remove_user_js_block(profile):
        removed.append('user.js block')
    for name in ('zen-material-you.css', 'zen-material-you-content.css'):
        path = os.path.join(chrome, name)
        if os.path.isfile(path):
            os.remove(path)
            removed.append('chrome/' + name)
    if remove_import(os.path.join(chrome, 'userChrome.css'), 'zen-material-you.css'):
        removed.append('chrome/userChrome.css import')
    if remove_import(
            os.path.join(chrome, 'userContent.css'), 'zen-material-you-content.css'):
        removed.append('chrome/userContent.css import')
    return removed


def ensure_import(path, target):
    """Prepend `@import url(target);` unless it is already there."""
    try:
        current = open(path).read()
    except FileNotFoundError:
        current = ''
    if target in current:
        return
    with open(path, 'w') as f:
        f.write('@import url("%s");\n' % target + current)


def main():
    profile = zen_profile()
    if not profile:
        print('zen-material-you: no Zen profile found, skipped')
        return 0

    if '--remove' in sys.argv[1:]:
        removed = remove_theme(profile)
        if removed:
            print('Zen theme removed from %s: %s' % (profile, ', '.join(removed)))
            print('Restart Zen to go back to the stock theme.')
        else:
            print('zen-material-you: nothing to remove in %s' % profile)
        return 0

    p = my.palette_or_die()
    c = colours(p)
    chrome = os.path.join(profile, 'chrome')
    os.makedirs(chrome, exist_ok=True)

    write_user_js(profile, c['accent'])
    with open(os.path.join(chrome, 'zen-material-you.css'), 'w') as f:
        f.write(user_chrome_css(c))
    with open(os.path.join(chrome, 'zen-material-you-content.css'), 'w') as f:
        f.write(user_content_css(c))
    ensure_import(os.path.join(chrome, 'userChrome.css'), 'zen-material-you.css')
    ensure_import(os.path.join(chrome, 'userContent.css'), 'zen-material-you-content.css')

    print('Zen theme written to %s/chrome (restart Zen to apply). accent=%s'
          % (profile, c['accent']))
    return 0


if __name__ == '__main__':
    sys.exit(main())
